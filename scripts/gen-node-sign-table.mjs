// INPUT: swisseph native module (backend/node_modules) — SE_TRUE_NODE longitudes.
// OUTPUT: writes data/nodeSignTable.ts (committed) — True Node sign ingresses
//         over RANGE_START..RANGE_END, consumed by utils/nodeSign.ts lookup.
// POS: Build-time codegen for the tool-led North-Node mini-calc. Run via
//      `npm run gen:node-sign-table`. FAILS HARD (exit 1) if swisseph is absent
//      or returns mock/degenerate data — the committed table must be real.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");

// Must match backend/src/data/sources.ts SIGNS exactly — the natal chart and
// the mini-calc have to report the same sign for the same date.
const SIGNS = [
  "Aries", "Taurus", "Gemini", "Cancer", "Leo", "Virgo",
  "Libra", "Scorpio", "Sagittarius", "Capricorn", "Aquarius", "Pisces",
];

const SE_TRUE_NODE = 11; // matches ephemeris.ts — True Node, not Mean Node.
const SEFLG_SPEED = 256;
const GREGORIAN = 1;

// Birth-date coverage. App targets 18-35yo (born ~1991-2008) but we generate a
// generous window so the calc works for parents/older cohorts and future years.
const RANGE_START = "1940-01-01";
const RANGE_END = "2035-12-31";

// Sanity floor: the True Node changes sign roughly every ~1.55yr, so a ~96yr
// window must yield well over 50 ingresses. A near-zero count means swisseph
// returned constant/mock data — fail rather than commit a useless table.
const MIN_EXPECTED_INGRESSES = 40;

// --- Load real swisseph or fail hard (assert-real-not-mock) -----------------
const nodeRequire = createRequire(join(repoRoot, "backend/"));
let swisseph;
try {
  const mod = nodeRequire("swisseph");
  swisseph = mod.default || mod;
} catch (err) {
  console.error(
    "FATAL: swisseph native module not available — cannot generate a real " +
      "node-sign table.",
  );
  console.error("Run `cd backend && npm install` so SE_TRUE_NODE can be computed.");
  console.error(String(err && err.message ? err.message : err));
  process.exit(1);
}

const pad = (n) => String(n).padStart(2, "0");
const toIso = (d) =>
  `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;

const signIndexForJd = (jd) => {
  const result = swisseph.swe_calc_ut(jd, SE_TRUE_NODE, SEFLG_SPEED);
  if (!result || result.error || !Number.isFinite(result.longitude)) {
    throw new Error(
      `swe_calc_ut returned no usable longitude (jd=${jd}): ${
        result && result.error ? result.error : "non-finite"
      }`,
    );
  }
  const lon = ((result.longitude % 360) + 360) % 360;
  return Math.floor(lon / 30);
};

// --- Walk every day, emit a record on each sign change ----------------------
const ingresses = [];
const start = new Date(`${RANGE_START}T00:00:00Z`);
const end = new Date(`${RANGE_END}T00:00:00Z`);
let prevSign = -1;

for (
  let cursor = new Date(start);
  cursor.getTime() <= end.getTime();
  cursor.setUTCDate(cursor.getUTCDate() + 1)
) {
  const jd = swisseph.swe_julday(
    cursor.getUTCFullYear(),
    cursor.getUTCMonth() + 1,
    cursor.getUTCDate(),
    0, // 00:00 UT
    GREGORIAN,
  );
  const signIndex = signIndexForJd(jd);
  if (signIndex !== prevSign) {
    ingresses.push({ date: toIso(cursor), sign: SIGNS[signIndex] });
    prevSign = signIndex;
  }
}

if (ingresses.length < MIN_EXPECTED_INGRESSES) {
  console.error(
    `FATAL: only ${ingresses.length} ingresses over ${RANGE_START}..${RANGE_END} ` +
      `(expected >= ${MIN_EXPECTED_INGRESSES}). swisseph likely returned ` +
      "mock/degenerate data — refusing to write the table.",
  );
  process.exit(1);
}

// --- Emit the committed TypeScript data module ------------------------------
const rows = ingresses
  .map((i) => `  { date: ${JSON.stringify(i.date)}, sign: ${JSON.stringify(i.sign)} },`)
  .join("\n");

const out = `// INPUT: generated by scripts/gen-node-sign-table.mjs from Swiss Ephemeris.
// OUTPUT: NODE_SIGN_TABLE — True Node (SE_TRUE_NODE) sign ingresses, sampled at
//         00:00 UT daily over ${RANGE_START}..${RANGE_END}. Consumed by utils/nodeSign.ts.
// POS: Generated data — DO NOT EDIT BY HAND. Regenerate with
//      \`npm run gen:node-sign-table\` (requires backend swisseph).

import type { NodeSignTable } from "../utils/nodeSign";

export const NODE_SIGN_TABLE: NodeSignTable = {
  node: "true",
  rangeStart: ${JSON.stringify(RANGE_START)},
  rangeEnd: ${JSON.stringify(RANGE_END)},
  ingresses: [
${rows}
  ],
};
`;

const outPath = join(repoRoot, "data", "nodeSignTable.ts");
writeFileSync(outPath, out, "utf8");
console.log(
  `Wrote ${outPath} — ${ingresses.length} True Node ingresses ` +
    `(${RANGE_START}..${RANGE_END}).`,
);
